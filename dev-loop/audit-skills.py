#!/usr/bin/env python3
"""Audit which core-tier external skills are ACTUALLY installed.

Trusts the filesystem, not SKILLS.md. Checks three locations Qoder reads:
  ~/.agents/skills/<name>      (universal install target)
  ~/.qoder/skills/<name>       (Qoder-native, may be a symlink)
  plugin-provided skills       (superpowers:*, ui-ux-pro-max-skill:*)

Writes a UTF-8 report; prints nothing that depends on console codepage.
"""
import json
import os
import re
import sys
from pathlib import Path

HOME = Path.home()
CORE = {
    "requirements": [
        ("prd-development", "deanpeters/Product-Manager-Skills"),
        ("product-strategy-session", "deanpeters/Product-Manager-Skills"),
        ("discovery-process", "deanpeters/Product-Manager-Skills"),
        ("prioritization-frameworks", "phuryn/pm-skills"),
        ("outcome-roadmap", "phuryn/pm-skills"),
    ],
    "design": [
        ("impeccable", "pbakaus/impeccable"),
        ("ui-ux-pro-max", "nextlevelbuilder/ui-ux-pro-max-skill"),
        ("web-design-guidelines", "vercel-labs/agent-skills"),
        ("review-animations", "emilkowalski/skills"),
    ],
    "engineering": [
        ("writing-plans", "obra/superpowers"),
        ("test-driven-development", "obra/superpowers"),
        ("systematic-debugging", "obra/superpowers"),
        ("requesting-code-review", "obra/superpowers"),
        ("verification-before-completion", "obra/superpowers"),
    ],
    "qa": [
        ("testing-strategy", "anthropics/knowledge-work-plugins"),
        ("qa-only", "garrytan/gstack"),
        ("code-review", "anthropics/knowledge-work-plugins"),
        ("playwright", "openai/skills"),
    ],
    "release": [
        ("ship", "garrytan/gstack"),
        ("github-actions-hardening", "github/awesome-copilot"),
    ],
    "retro": [
        ("incident-response", "rampstackco/claude-skills"),
        ("metrics-review", "anthropics/knowledge-work-plugins"),
        ("analyzing-user-feedback", "refoundai/lenny-skills"),
        ("validate-data", "anthropics/knowledge-work-plugins"),
        ("craft-experiment-design", "amplitude/builder-skills"),
        # recommended tier, but SKILL.md's step-6 routing names it, so it must exist
        ("retro", "garrytan/gstack"),
    ],
}

SEARCH_ROOTS = [
    HOME / ".agents" / "skills",
    HOME / ".qoder" / "skills",
    HOME / ".claude" / "skills",
]
PLUGIN_ROOTS = [
    HOME / ".qoder" / "plugins",
]


def has_skill_md(p: Path) -> bool:
    """A directory counts as an installed skill only if SKILL.md exists."""
    return (p / "SKILL.md").is_file()


def find(name: str):
    hits = []
    for root in SEARCH_ROOTS:
        cand = root / name
        if cand.exists() and has_skill_md(cand):
            kind = "symlink" if cand.is_symlink() else "dir"
            hits.append(f"{root.name}/{name} ({kind})")
    for root in PLUGIN_ROOTS:
        if not root.is_dir():
            continue
        for cand in root.rglob(name):
            if cand.is_dir() and has_skill_md(cand):
                rel = cand.relative_to(HOME)
                hits.append(str(rel))
                break
    return hits


def main() -> int:
    lines = []
    total = 0
    ok = 0
    missing = []
    for domain, entries in CORE.items():
        lines.append(f"\n## {domain}")
        for name, repo in entries:
            total += 1
            hits = find(name)
            if hits:
                ok += 1
                lines.append(f"  [OK]      {name:<34} <- {repo}")
                lines.append(f"            at: {hits[0]}")
            else:
                missing.append((name, repo, domain))
                lines.append(f"  [MISSING] {name:<34} <- {repo}")

    header = [
        "# Core-tier skill install audit",
        f"generated by dev-loop/audit-skills.py",
        f"installed: {ok}/{total}",
    ]
    if missing:
        header.append(f"missing  : {len(missing)}")
        for name, repo, domain in missing:
            header.append(f"   - {name} ({domain}) <- {repo}")
    else:
        header.append("missing  : 0  -- core chain complete")

    out = Path("audit-report.md")
    out.write_text("\n".join(header + lines) + "\n", encoding="utf-8")
    sys.stdout.write(f"wrote {out} : {ok}/{total} installed, {len(missing)} missing\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
